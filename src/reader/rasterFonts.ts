import { init, subset } from 'hb-subset-wasm';
import wasmUrl from 'hb-subset-wasm/hb-subset.wasm?url';

export function base64(bytes: Uint8Array) {
  let binary = '';
  for (let i = 0; i < bytes.length; i += 0x8000) binary += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  return btoa(binary);
}

async function loadBytes(url: string) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`载入翻页字体资源失败（HTTP ${response.status}）`);
  return response.arrayBuffer();
}

let font: Promise<Uint8Array> | undefined;
export async function miSansPageFace(text: string) {
  font ??= Promise.all([loadBytes('/fonts/MiSansVF.ttf'), loadBytes(wasmUrl).then(init)])
    .then(([bytes]) => new Uint8Array(bytes))
    .catch(error => { font = undefined; throw error; });
  // Include list markers and transformed Latin text generated by the page stylesheet.
  const bytes = await subset(await font, { text: text + text.toUpperCase() + '0123456789. •', layoutFeatures: '*' });
  return `@font-face{font-family:MiSans;src:url(data:font/ttf;base64,${base64(bytes)}) format('truetype');font-weight:150 700}`;
}
